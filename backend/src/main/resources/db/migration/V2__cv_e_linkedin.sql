-- versioni del CV caricate come file (PDF, DOC, DOCX), una o piu' per account
CREATE TABLE cv (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_account       BIGINT                   NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    nome             VARCHAR(255)             NOT NULL,
    nome_file        VARCHAR(255)             NOT NULL,
    content_type     VARCHAR(255)             NOT NULL,
    dimensione       BIGINT                   NOT NULL,
    contenuto        BYTEA                    NOT NULL,
    data_caricamento TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_cv_id_account ON cv (id_account);

-- link al profilo LinkedIn, facoltativo
ALTER TABLE account ADD COLUMN linkedin VARCHAR(255);
