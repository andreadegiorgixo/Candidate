CREATE TABLE account (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(255) NOT NULL,
    cognome        VARCHAR(255) NOT NULL,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password       VARCHAR(255) NOT NULL,
    data_creazione DATE         NOT NULL
);

CREATE TABLE citta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_citta VARCHAR(255) NOT NULL,
    provincia  VARCHAR(255) NOT NULL,
    regione    VARCHAR(255) NOT NULL,
    nazione    VARCHAR(255) NOT NULL,
    CONSTRAINT uq_citta_nome_provincia UNIQUE (nome_citta, provincia)
);

CREATE TABLE candidature (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_account           BIGINT       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    nome_azienda         VARCHAR(255) NOT NULL,
    posizione_lavorativa VARCHAR(255) NOT NULL,
    job_offert           TEXT         NOT NULL,
    modalita             VARCHAR(20)  NOT NULL,
    id_citta             BIGINT       NOT NULL REFERENCES citta (id),
    stato_candidatura    VARCHAR(50)  NOT NULL,
    data_candidatura     DATE         NOT NULL,
    note                 TEXT,
    data_creazione       DATE         NOT NULL
);

CREATE INDEX idx_candidature_id_account ON candidature (id_account);
CREATE INDEX idx_candidature_id_citta ON candidature (id_citta);
